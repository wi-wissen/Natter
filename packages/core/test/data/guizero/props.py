from guizero import *


def show(label, f):
    try:
        print(label, repr(f()))
    except Exception as e:
        print(label, "EXC", type(e).__name__, str(e).replace("\n", "|"))


def setget(label, w, name, value):
    show(label, lambda: (setattr(w, name, value), getattr(w, name))[1])


